// Tier 3: drive the served web app through the same scenario steps as scenario_qt.py.
//
// Addressed entirely through the accessibility overlay — `?a11y=pointer` makes the
// proxies the hit target, so a menu item is found by role and name and clicked like
// any DOM element. That is the same route `tests/a11y_browser_validate.ts` proved
// works end to end, and it is what makes a canvas app drivable at all.
//
// The plan is produced by run_scenarios.py rather than read from the scenario files:
// the Qt-worded menu paths have already been resolved to this side's labels there, so
// exactly one map between the two vocabularies exists and it is the same one tier 2
// uses.
//
//   bun tests/parity/scenario_web.ts --plan <plan.json> --out <snapshots.json>

import { readFileSync, writeFileSync } from "node:fs";

import { chromium, type Page } from "playwright";

import { pressKey } from "./parity_keys";

const BASE_URL = process.env.SNUFFLER_BROWSER_URL || "http://127.0.0.1:17683/";
const HEADLESS = process.env.SNUFFLER_BROWSER_HEADLESS !== "0";
const BOOT_TIMEOUT_MS = Number(process.env.SNUFFLER_BROWSER_TEST_TIMEOUT_MS || 300_000);
const OVERLAY = "#snuffler-a11y";

interface PlanStep {
  action: "menu" | "key" | "filter" | "pick";
  label: string;
  menu?: string;
  item?: string;
  key?: string;
  highpass?: number | null;
  lowpass?: number | null;
  x?: number;
  y?: number;
}

interface Plan {
  name: string;
  watchMenus: string[];
  steps: PlanStep[];
}

interface MarkerRow {
  kind: number;
  nslc: string[];
  phase: string;
  polarity: number | null;
  selected: boolean;
  time: string;
}

interface Snapshot {
  step: string;
  menu_state: Record<string, boolean>;
  controls: Record<string, number | null>;
  markers: MarkerRow[];
  selected_count: number;
}

function url(params: Record<string, string>): string {
  const target = new URL(BASE_URL);
  for (const [key, value] of Object.entries(params)) target.searchParams.set(key, value);
  return target.toString();
}

async function boot(page: Page): Promise<void> {
  await page.goto(url({ a11y: "pointer" }), { waitUntil: "load" });
  await page
    .getByText("Importing pyrocko...")
    .first()
    .waitFor({ state: "hidden", timeout: BOOT_TIMEOUT_MS });
  await page.waitForTimeout(2500);
}

async function openMenu(page: Page, menu: string): Promise<void> {
  await page.getByRole("button", { name: menu, exact: true }).first().click();
  await page.waitForTimeout(400);
}

/// Close a menu by clicking its own button again.
///
/// There is nowhere neutral to click instead: with `?a11y=pointer` the proxies are the
/// hit target, so a click anywhere in the menu bar lands on a menu button, and a click
/// in the waveform area is a click *on the waveform*. Escape is worse — egui lets it
/// through to the app, which reads it as "enter batch picking".
///
/// Plain buttons close the menu themselves (`ui.close()`); checkboxes do not, which is
/// why this checks before it clicks.
async function closeMenu(page: Page, menu: string, probeItem: string): Promise<void> {
  const open = await page.$(`${OVERLAY} [aria-label="${probeItem}"]`);
  if (open) await openMenu(page, menu);
}

/// The whole loaded dataset, through the File menu — the same synthetic demo the Qt
/// side loads from the corpus, generated by the same code with the same seed.
async function loadExample(page: Page): Promise<void> {
  await openMenu(page, "File");
  await page.getByRole("button", { name: "Synthetic example" }).first().click();
  await page.waitForTimeout(5000);
  await closeMenu(page, "File", "Synthetic example");
}

/// Read one control-strip field back the way it is displayed.
async function fieldValue(page: Page, field: string): Promise<string> {
  const values = await page.$$eval(`${OVERLAY} [role=textbox]`, (els) =>
    els.map((el): [string, string] => {
      const via = el.getAttribute("aria-labelledby");
      const label = via ? (document.getElementById(via)?.textContent ?? "") : "";
      return [label.trim(), (el.textContent ?? "").trim()];
    })
  );
  return values.find(([label]) => label === field)?.[1] ?? "";
}

/// Type a value into one of the control-strip fields.
///
/// Deliberately unhurried, and verified afterwards. egui consumes input a frame at a
/// time, so a click, a select-all and a burst of keystrokes sent back to back can
/// arrive before the field has taken focus, and the characters land nowhere — with no
/// error, just a value that did not change.
async function setFilter(page: Page, field: string, value: number): Promise<void> {
  // The fields carry no name of their own; they borrow the label painted beside them,
  // which is exactly how a screen reader finds them too.
  for (let attempt = 0; attempt < 3; attempt += 1) {
    await page.getByRole("textbox", { name: field }).first().click();
    await page.waitForTimeout(350);
    await page.keyboard.press("ControlOrMeta+a");
    await page.waitForTimeout(150);
    await page.keyboard.type(String(value), { delay: 60 });
    await page.waitForTimeout(300);
    await page.keyboard.press("Enter");
    await page.waitForTimeout(500);
    const shown = await fieldValue(page, field);
    if (shown !== "" && Number(shown) === value) return;
  }
  throw new Error(`${field} would not take the value ${value}`);
}

async function applyStep(page: Page, step: PlanStep): Promise<void> {
  if (step.action === "menu") {
    await openMenu(page, step.menu!);
    await page
      .getByRole("checkbox", { name: step.item!, exact: true })
      .first()
      .click()
      .catch(async () => {
        await page.getByRole("button", { name: step.item!, exact: true }).first().click();
      });
    await page.waitForTimeout(400);
    await closeMenu(page, step.menu!, step.item!);
    return;
  }
  if (step.action === "key") {
    // No canvas click first, on purpose. Single-key shortcuts have to keep working
    // after a menu is operated from the accessibility layer — a driver that clicks
    // the canvas before every keystroke would paper over exactly the kind of dead
    // keyboard a screen-reader user would be left with.
    await pressKey(page.keyboard, step.key!);
    await page.waitForTimeout(500);
    return;
  }
  if (step.action === "filter") {
    if (step.highpass != null) await setFilter(page, "Highpass [Hz]:", step.highpass);
    if (step.lowpass != null) await setFilter(page, "Lowpass [Hz]:", step.lowpass);
    return;
  }
  if (step.action === "pick") {
    const box = await page.locator("#the_canvas_id").boundingBox();
    if (!box) throw new Error("canvas has no box");
    // Same convention as the Qt driver: a fraction of the waveform area, with the
    // panels above and below left out. The two layouts still put different data under
    // that point, which is why the diff compares what the marker is, not where it is.
    const top = 34;
    const bottom = 210;
    await page.locator("#the_canvas_id").dblclick({
      position: {
        x: (step.x ?? 0.5) * box.width,
        y: top + (step.y ?? 0.5) * (box.height - top - bottom),
      },
    });
    await page.waitForTimeout(900);
    return;
  }
  throw new Error(`unknown action ${step.action}`);
}

async function readMenuState(page: Page, menus: string[]): Promise<Record<string, boolean>> {
  const state: Record<string, boolean> = {};
  for (const menu of menus) {
    await openMenu(page, menu);
    const boxes = await page.$$eval(`${OVERLAY} [role=checkbox]`, (els) =>
      els.map((el) => [el.getAttribute("aria-label") ?? "", el.getAttribute("aria-checked")])
    );
    for (const [name, checked] of boxes) {
      if (name) state[`${menu}/${name}`] = checked === "true";
    }
    await openMenu(page, menu);
  }
  return state;
}

async function readControls(page: Page): Promise<Record<string, number | null>> {
  const raw = await page.$$eval(`${OVERLAY} [role=textbox]`, (els) =>
    els.map((el): [string, string] => {
      const via = el.getAttribute("aria-labelledby");
      const label = via ? (document.getElementById(via)?.textContent ?? "") : "";
      return [label.trim(), (el.textContent ?? "").trim()];
    })
  );
  const named = new Map<string, string>(raw);
  const value = (label: string): number | null => {
    const text = named.get(label);
    if (text === undefined || text === "" || text.toLowerCase() === "off") return null;
    const parsed = Number(text);
    return Number.isFinite(parsed) ? parsed : null;
  };
  return {
    highpass: value("Highpass [Hz]:"),
    lowpass: value("Lowpass [Hz]:"),
    gain: value("Gain:"),
    rotate: value("Rotate [deg]:"),
  };
}

/// The marker table, which the app publishes in full once the Marker editor is open.
///
/// Rows are a flat run of grid cells, so they are split on the type symbol each row
/// starts with: ● for a plain marker, ▲ for an event marker. Selection is read off
/// the row's own `aria-selected`, and the table's "N markers · M selected" summary is
/// kept as a cross-check that the two agree.
async function readMarkers(page: Page): Promise<{ rows: MarkerRow[]; selected: number }> {
  const cells = await page.evaluate(() => {
    const dialogs = [...document.querySelectorAll("#snuffler-a11y [role=dialog]")];
    const table = dialogs.find((d) => d.getAttribute("aria-label") === "Markers");
    if (!table) return null;
    return [...table.querySelectorAll("[data-ak]")]
      .filter((el) => el.querySelector("[data-ak]") === null)
      .map((el) => ({
        text: (el.getAttribute("aria-label") ?? el.textContent ?? "").trim(),
        selected: el.getAttribute("aria-selected"),
      }));
  });
  if (cells === null) throw new Error("the Markers window is not open");

  const summary = cells.find((c) => /·\s+\d+ selected/.test(c.text))?.text ?? "";
  const selected = Number(/·\s+(\d+) selected/.exec(summary)?.[1] ?? 0);

  const rows: MarkerRow[] = [];
  for (let i = 0; i < cells.length; i += 1) {
    const symbol = cells[i]?.text;
    if (symbol !== "●" && symbol !== "▲") continue;
    const cell = (offset: number): string => cells[i + offset]?.text ?? "";
    const polarity = cell(4);
    rows.push({
      kind: Number(cell(5)) || 0,
      nslc: cell(6) === "—" ? [] : [cell(6)],
      phase: cell(3) === "—" ? "" : cell(3),
      polarity: polarity === "—" ? null : Number(polarity),
      selected: cells[i]?.selected === "true",
      time: cell(1),
    });
    // A row is fourteen grid cells wide; step past it rather than rescanning it.
    i += 13;
  }

  const flagged = rows.filter((row) => row.selected).length;
  if (rows.length > 0 && flagged !== selected) {
    throw new Error(`marker rows report ${flagged} selected but the summary says ${selected}`);
  }
  return { rows, selected };
}

async function snapshot(page: Page, label: string, menus: string[]): Promise<Snapshot> {
  const { rows, selected } = await readMarkers(page);
  rows.sort(
    (a, b) =>
      a.kind - b.kind ||
      a.nslc.join().localeCompare(b.nslc.join()) ||
      a.phase.localeCompare(b.phase)
  );
  return {
    step: label,
    menu_state: await readMenuState(page, menus),
    controls: await readControls(page),
    markers: rows,
    selected_count: selected,
  };
}

async function main(): Promise<void> {
  const argOf = (flag: string): string | undefined => {
    const index = process.argv.indexOf(flag);
    return index >= 0 ? process.argv[index + 1] : undefined;
  };
  const planPath = argOf("--plan");
  const outPath = argOf("--out");
  if (!planPath) throw new Error("--plan is required");
  const plans = JSON.parse(readFileSync(planPath, "utf8")) as Plan[];

  const browser = await chromium.launch({ headless: HEADLESS });
  const page = await browser.newPage();
  await page.setViewportSize({ width: 1600, height: 1000 });
  const result: Record<string, Snapshot[]> = {};
  try {
    for (const plan of plans) {
      await boot(page);
      await loadExample(page);
      // The marker table is where marker state is readable, so it stays open for the
      // whole run rather than being toggled around each snapshot.
      await openMenu(page, "View");
      await page.getByRole("checkbox", { name: "Marker editor", exact: true }).first().click();
      await page.waitForTimeout(600);
      await closeMenu(page, "View", "Marker editor");

      const snapshots = [await snapshot(page, "start", plan.watchMenus)];
      for (const step of plan.steps) {
        await applyStep(page, step);
        snapshots.push(await snapshot(page, step.label, plan.watchMenus));
      }
      result[plan.name] = snapshots;
    }
  } finally {
    await browser.close();
  }

  const text = `${JSON.stringify(result, null, 2)}\n`;
  if (outPath) {
    writeFileSync(outPath, text);
    console.log(`web scenarios: ${Object.keys(result).length} -> ${outPath}`);
  } else {
    process.stdout.write(text);
  }
}

await main();
