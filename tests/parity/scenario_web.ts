// Tier 3: drive the served web app through the same scenario steps as scenario_qt.py.
//
// Addressed entirely through the accessibility overlay.
// `?a11y=pointer` makes the proxies the hit target, so a menu item is found by role
// and name and clicked like any DOM element.
// That is the route `tests/a11y_browser_validate.ts` proved works end to end, and it
// is what makes a canvas app drivable at all.
//
// The plan is produced by run_scenarios.py rather than read from the scenario files.
// The Qt-worded menu paths have already been resolved to this side's labels there,
// so exactly one map between the two vocabularies exists, the same one tier 2 uses.
//
//   bun tests/parity/scenario_web.ts --plan <plan.json> --out <snapshots.json>

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { type Page } from "playwright";

import {
  appUrl,
  BOOT_TIMEOUT_MS,
  closeWebMenu,
  launchParityBrowser,
  reportParityRenderer,
  saveWebScreenshots,
  waitForAppReady,
} from "./parity_browser";
import { pressKey } from "./parity_keys";

const OVERLAY = "#snuffler-a11y";

interface PlanStep {
  action: "menu" | "key" | "filter" | "pick";
  label: string;
  menu?: string;
  item?: string;
  key?: string;
  highpass?: number | null;
  lowpass?: number | null;
  x?: number;
  y?: number;
}

interface Plan {
  name: string;
  watchMenus: string[];
  steps: PlanStep[];
}

interface MarkerRow {
  kind: number;
  nslc: string[];
  phase: string;
  polarity: number | null;
  selected: boolean;
  time: string;
}

interface Snapshot {
  step: string;
  menu_state: Record<string, boolean>;
  controls: Record<string, number | null>;
  markers: MarkerRow[];
  selected_count: number;
}

async function boot(page: Page): Promise<void> {
  await page.goto(appUrl({ a11y: "pointer", demo: "1" }), { waitUntil: "load" });
  await page
    .getByText("Importing pyrocko...")
    .first()
    .waitFor({ state: "hidden", timeout: BOOT_TIMEOUT_MS });
  await waitForAppReady(page);
}

async function openMenu(page: Page, menu: string): Promise<void> {
  await page.getByRole("button", { name: menu, exact: true }).first().click();
  await page.waitForTimeout(400);
}

// Wait for the synthetic demo the app was booted on.
// The Qt side loads the same one from the corpus, generated by the same code with
// the same seed.
//
// Requested as `?demo=1` at boot, because the File menu does not offer it.
// The app opens on a real recording, and the synthetic pile stays reachable for
// exactly this comparison.
async function loadExample(page: Page): Promise<void> {
  // The demo is requested before the worker boots, so wait for the application
  // lifecycle rather than visible wording or a machine-dependent delay.
  await waitForAppReady(page);
}

// Every control-strip text field as [borrowed label, displayed text], in page order.
async function readLabelledFields(page: Page): Promise<Array<[string, string]>> {
  return await page.$$eval(`${OVERLAY} [role=textbox]`, (textboxes) =>
    textboxes.map((textbox): [string, string] => {
      const labelId = textbox.getAttribute("aria-labelledby");
      const label = labelId ? (document.getElementById(labelId)?.textContent ?? "") : "";
      return [label.trim(), (textbox.textContent ?? "").trim()];
    })
  );
}

// Read one control-strip field back the way it is displayed.
async function fieldValue(page: Page, field: string): Promise<string> {
  const fields = await readLabelledFields(page);
  return fields.find(([label]) => label === field)?.[1] ?? "";
}

// Type a value into one of the control-strip fields.
//
// Deliberately unhurried, and verified afterwards.
// egui consumes input a frame at a time, so a click, a select-all and a burst of
// keystrokes sent back to back can arrive before the field has taken focus.
// The characters then land nowhere, with no error, just a value that did not change.
async function setFilter(page: Page, field: string, value: number): Promise<void> {
  // The fields carry no name of their own; they borrow the label painted beside them.
  // That is exactly how a screen reader finds them too.
  for (let attempt = 0; attempt < 3; attempt += 1) {
    await page.getByRole("textbox", { name: field }).first().click();
    await page.waitForTimeout(350);
    await page.keyboard.press("ControlOrMeta+a");
    await page.waitForTimeout(150);
    await page.keyboard.type(String(value), { delay: 60 });
    await page.waitForTimeout(300);
    await page.keyboard.press("Enter");
    await page.waitForTimeout(500);
    const shown = await fieldValue(page, field);
    if (shown !== "" && Number(shown) === value) return;
  }
  throw new Error(`${field} would not take the value ${value}`);
}

async function applyStep(page: Page, step: PlanStep): Promise<void> {
  if (step.action === "menu") {
    await openMenu(page, step.menu!);
    await page
      .getByRole("checkbox", { name: step.item!, exact: true })
      .first()
      .click()
      .catch(async () => {
        await page.getByRole("button", { name: step.item!, exact: true }).first().click();
      });
    await page.waitForTimeout(400);
    await closeWebMenu(page, step.menu!, step.item!);
    return;
  }
  if (step.action === "key") {
    // No canvas click first, on purpose.
    // Single-key shortcuts have to keep working after a menu is operated from the
    // accessibility layer.
    // A driver that clicks the canvas before every keystroke would paper over exactly
    // the kind of dead keyboard a screen-reader user would be left with.
    await pressKey(page.keyboard, step.key!);
    await page.waitForTimeout(500);
    return;
  }
  if (step.action === "filter") {
    if (step.highpass != null) await setFilter(page, "Highpass [Hz]:", step.highpass);
    if (step.lowpass != null) await setFilter(page, "Lowpass [Hz]:", step.lowpass);
    return;
  }
  if (step.action === "pick") {
    const canvasBox = await page.locator("#the_canvas_id").boundingBox();
    if (!canvasBox) throw new Error("canvas has no box");
    // Same convention as the Qt driver: a fraction of the waveform area, with the
    // panels above and below left out.
    // The two layouts still put different data under that point, which is why the
    // diff compares what the marker is, not where it is.
    const topPanelPx = 34;
    const bottomPanelPx = 210;
    const position = {
      x: (step.x ?? 0.5) * canvasBox.width,
      y: topPanelPx + (step.y ?? 0.5) * (canvasBox.height - topPanelPx - bottomPanelPx),
    };
    // The double-click *arms* picking, as Qt's does: a floating pick follows the
    // cursor and the next press-release commits it.
    // The pause between the two keeps the commit click outside egui's double-click
    // window, where it would otherwise read as a triple click.
    await page.locator("#the_canvas_id").dblclick({ position });
    await page.waitForTimeout(600);
    await page.locator("#the_canvas_id").click({ position });
    await page.waitForTimeout(900);
    return;
  }
  throw new Error(`unknown action ${step.action}`);
}

async function readMenuState(page: Page, menus: string[]): Promise<Record<string, boolean>> {
  const state: Record<string, boolean> = {};
  for (const menu of menus) {
    await openMenu(page, menu);
    const checkboxes = await page.$$eval(`${OVERLAY} [role=checkbox]`, (elements) =>
      elements.map((checkbox) => [
        checkbox.getAttribute("aria-label") ?? "",
        checkbox.getAttribute("aria-checked"),
      ])
    );
    for (const [name, checked] of checkboxes) {
      if (name) state[`${menu}/${name}`] = checked === "true";
    }
    await openMenu(page, menu);
  }
  return state;
}

async function readControls(page: Page): Promise<Record<string, number | null>> {
  const named = new Map<string, string>(await readLabelledFields(page));
  const value = (label: string): number | null => {
    const text = named.get(label);
    if (text === undefined || text === "" || text.toLowerCase() === "off") return null;
    const parsed = Number(text);
    return Number.isFinite(parsed) ? parsed : null;
  };
  return {
    highpass: value("Highpass [Hz]:"),
    lowpass: value("Lowpass [Hz]:"),
    gain: value("Gain:"),
    rotate: value("Rotate [deg]:"),
  };
}

// The marker table, which the app publishes in full once the Markers panel is open.
//
// Rows are a flat run of grid cells, so they are split on the type symbol each row
// starts with: ● for a plain marker, ▲ for an event marker.
// Selection is read off the row's own `aria-selected`.
// The table's "N markers · M selected" summary is kept as a cross-check that the two
// agree.
async function readMarkers(page: Page): Promise<{ rows: MarkerRow[]; selected: number }> {
  const cells = await page.evaluate(() => {
    const dialogs = [...document.querySelectorAll("#snuffler-a11y [role=dialog]")];
    const table = dialogs.find((dialog) => dialog.getAttribute("aria-label") === "Markers");
    if (!table) return null;
    return [...table.querySelectorAll("[data-ak]")]
      .filter((element) => element.querySelector("[data-ak]") === null)
      .map((cell) => ({
        text: (cell.getAttribute("aria-label") ?? cell.textContent ?? "").trim(),
        selected: cell.getAttribute("aria-selected"),
      }));
  });
  if (cells === null) throw new Error("the Markers window is not open");

  const summary = cells.find((cell) => /·\s+\d+ selected/.test(cell.text))?.text ?? "";
  const selected = Number(/·\s+(\d+) selected/.exec(summary)?.[1] ?? 0);

  const rows: MarkerRow[] = [];
  for (let rowStart = 0; rowStart < cells.length; rowStart += 1) {
    const symbol = cells[rowStart]?.text;
    if (symbol !== "●" && symbol !== "▲") continue;
    const cell = (column: number): string => cells[rowStart + column]?.text ?? "";
    const polarity = cell(4);
    const nslcs = cell(7);
    rows.push({
      kind: Number(cell(6)) || 0,
      nslc: nslcs === "" || nslcs === "—" ? [] : nslcs.split("|"),
      phase: cell(3) === "—" ? "" : cell(3),
      polarity: polarity === "—" ? null : Number(polarity),
      selected: cells[rowStart]?.selected === "true",
      time: cell(1),
    });
    // A row is sixteen grid cells wide (symbol, time, span, label, pol, unc,
    // kind, NSLCs, dist, Kagan, mag, depth, lat, lon, hash, actions).
    // Step past it rather than rescanning it.
    rowStart += 15;
  }

  const flagged = rows.filter((row) => row.selected).length;
  if (rows.length > 0 && flagged !== selected) {
    throw new Error(`marker rows report ${flagged} selected but the summary says ${selected}`);
  }
  return { rows, selected };
}

async function snapshot(page: Page, label: string, menus: string[]): Promise<Snapshot> {
  const { rows, selected } = await readMarkers(page);
  rows.sort(
    (a, b) =>
      a.kind - b.kind ||
      a.nslc.join().localeCompare(b.nslc.join()) ||
      a.phase.localeCompare(b.phase)
  );
  return {
    step: label,
    menu_state: await readMenuState(page, menus),
    controls: await readControls(page),
    markers: rows,
    selected_count: selected,
  };
}

// The value following `flag` on the command line, if the flag is present.
function argumentValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

async function main(): Promise<void> {
  const planPath = argumentValue("--plan");
  const outPath = argumentValue("--out");
  const screenshotsPath = argumentValue("--screenshots");
  if (!planPath) throw new Error("--plan is required");
  const plans = JSON.parse(readFileSync(planPath, "utf8")) as Plan[];

  const browser = await launchParityBrowser();
  const page = await browser.newPage();
  await page.setViewportSize({ width: 1600, height: 1000 });
  const snapshotsByPlan: Record<string, Snapshot[]> = {};
  let rendererReported = false;
  try {
    for (const plan of plans) {
      await boot(page);
      if (!rendererReported) {
        await reportParityRenderer(page);
        rendererReported = true;
      }
      await loadExample(page);
      // The marker table is where marker state is readable, so it stays open for the
      // whole run rather than being toggled around each snapshot.
      await openMenu(page, "Snufflings");
      await page.getByRole("checkbox", { name: "Markers", exact: true }).first().click();
      await page.waitForTimeout(600);
      await closeWebMenu(page, "Snufflings", "Markers");

      const snapshots = [await snapshot(page, "start", plan.watchMenus)];
      for (const step of plan.steps) {
        await applyStep(page, step);
        snapshots.push(await snapshot(page, step.label, plan.watchMenus));
      }
      snapshotsByPlan[plan.name] = snapshots;
      if (screenshotsPath) {
        await saveWebScreenshots(page, join(screenshotsPath, plan.name));
      }
    }
  } finally {
    await browser.close();
  }

  const text = `${JSON.stringify(snapshotsByPlan, null, 2)}\n`;
  if (outPath) {
    writeFileSync(outPath, text);
    console.log(`web scenarios: ${Object.keys(snapshotsByPlan).length} -> ${outPath}`);
  } else {
    process.stdout.write(text);
  }
}

await main();
